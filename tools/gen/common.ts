import type { Analysis, MessageFormatElement } from "../lib/icu.ts";
import { TYPE } from "../lib/icu.ts";
import { inScope, type PlaceholderType, type Platform, type SourceEntry } from "../lib/catalog.ts";
import { shipsOn, type Locale, type Locales, type PseudoLocale } from "../lib/locales.ts";

export interface GenInput {
  version: string;
  locales: Locales;
  /** Valid English entries in en.arb order. */
  entries: SourceEntry[];
  english: Map<string, Analysis>;
  /** Valid translations: tag -> key -> analysis. */
  translations: Map<string, Map<string, Analysis>>;
  /** Pseudo-locale messages: tag -> key -> analysis (web). */
  pseudo: Map<string, Map<string, Analysis>>;
  /** The same for Roku, whose en-XA uses brackets its font can draw. */
  rokuPseudo: Map<string, Map<string, Analysis>>;
}

export interface Language {
  locale: Locale | PseudoLocale;
  /** Valid messages by key; undefined when the language has no catalog file yet. */
  messages?: Map<string, Analysis>;
  pseudo: boolean;
}

/**
 * The languages a platform ships, source first, then targets, then (when `withPseudo`) the
 * pseudo-locales. A target ships on a platform only when locales.json allows it there and it has
 * at least one valid translation of a key in that platform's scope: generators write
 * no file for any other language, so "shipped" can be read off the generated files.
 */
export function languagesFor(input: GenInput, platform: Platform, withPseudo: boolean): Language[] {
  const scoped = input.entries.filter((e) => inScope(e, platform));
  const translated = (messages?: Map<string, Analysis>) => scoped.some((e) => messages?.has(e.key));
  const out: Language[] = [
    { locale: input.locales.source, messages: input.english, pseudo: false },
    ...input.locales.targets
      .map((l) => ({ locale: l, messages: input.translations.get(l.tag), pseudo: false }))
      .filter((l) => translated(l.messages)),
  ];
  if (withPseudo) out.push(...input.locales.pseudo.map((l) => ({ locale: l, messages: input.pseudo.get(l.tag), pseudo: true })));
  return out.filter((l) => shipsOn(l.locale, platform));
}

/** Relative path inside the platform's tree -> file content. */
export type Files = Map<string, string>;

export function header(version: string): string {
  return `Generated by silo-translations ${version} from catalog/*.arb; do not edit.`;
}

export interface RenderOptions {
  literal(text: string): string;
  arg(name: string): string;
  pound(): string;
}

/** Renders a shared-subset element list (literals, arguments, #). */
export function render(elements: MessageFormatElement[], o: RenderOptions): string {
  let out = "";
  for (const el of elements) {
    if (el.type === TYPE.literal) out += o.literal(el.value);
    else if (el.type === TYPE.argument) out += o.arg(el.value);
    else if (el.type === TYPE.pound) out += o.pound();
    else throw new Error(`element type ${TYPE[el.type]} is outside the shared subset`);
  }
  return out;
}

/** 1-based positional index of each placeholder, in en.arb declaration order. */
export function positions(entry: SourceEntry): Map<string, number> {
  return new Map(entry.placeholders.map((p, i) => [p.name, i + 1]));
}

/** A function from placeholder name to its positional specifier, such as `%2$lld`. */
export function positional(entry: SourceEntry, specifiers: Record<PlaceholderType, string>): (name: string) => string {
  const pos = positions(entry);
  return (name) => `%${pos.get(name)}$${specifiers[entry.placeholders[pos.get(name)! - 1]!.type]}`;
}

/** True when literal text anywhere in the message contains `%`. */
export function hasPercent(elements: MessageFormatElement[]): boolean {
  return elements.some((el) => {
    if (el.type === TYPE.literal) return el.value.includes("%");
    if (el.type === TYPE.plural) return Object.values(el.options).some((o) => hasPercent(o.value));
    return false;
  });
}

/**
 * Bidirectional control characters (ALM, LRM, RLM, the embeddings and overrides, the isolates).
 * Repositories that vendor the output refuse them as literal characters, so generated files
 * carry them only as escapes that decode to the same string.
 */
export const BIDI_CONTROL = /[\u061C\u200E\u200F\u202A-\u202E\u2066-\u2069]/;
const BIDI_CONTROLS = new RegExp(BIDI_CONTROL.source, "g");

/** Writes each bidi control as a \uXXXX escape. Only for text where that escape means the character. */
export function escapeBidi(text: string): string {
  return text.replace(BIDI_CONTROLS, (c) => `\\u${c.charCodeAt(0).toString(16).toUpperCase().padStart(4, "0")}`);
}

/** The generated files that contain a literal bidi control, with the first one's code point. */
export function literalBidi(files: Files): { path: string; codePoint: string }[] {
  const found: { path: string; codePoint: string }[] = [];
  for (const [path, text] of files) {
    const m = BIDI_CONTROL.exec(text);
    if (m) found.push({ path, codePoint: `U+${m[0].charCodeAt(0).toString(16).toUpperCase().padStart(4, "0")}` });
  }
  return found;
}

/** Pretty JSON with a trailing newline. Bidi controls are \uXXXX escapes. */
export function json(value: unknown): string {
  return escapeBidi(JSON.stringify(value, null, 2)) + "\n";
}
